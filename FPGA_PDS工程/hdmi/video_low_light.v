wire complete_frame=started && !bad_frame && !width_bad && !de &&
                         completed_rows==HEIGHT && frame_pixels==WIDTH*HEIGHT;
wire [15:0] r_wide={8'd0,r},g_wide={8'd0,g},b_wide={8'd0,b};
// Exact 77/150/29 coefficients with balanced add trees, no DSP multipliers.
wire [15:0] luminance_r=((r_wide<<6)+(r_wide<<3))+((r_wide<<2)+r_wide);
wire [15:0] luminance_g=((g_wide<<7)+(g_wide<<4))+((g_wide<<2)+(g_wide<<1));
wire [15:0] luminance_b=((b_wide<<4)+(b_wide<<3))+((b_wide<<2)+b_wide);
