    if(!rst_n) begin
        vs_d<=0; de_d<=0; started<=0; bad_frame<=0; map_valid<=0;
        x<=0; y<=0; local_x<=0; local_y<=0; tile_x<=0; tile_y<=0;
        frame_pixels<=0; accepted_frames<=0; rejected_frames<=0;
        frame_mode<=0; frame_manual<=0;
        for(stat_index=0;stat_index<CELLS;stat_index=stat_index+1) begin
            sums[stat_index]<=0; shadow_counts[stat_index]<=0; strengths[stat_index]<=0;
        end
    end else if(!rx_ready) begin
        vs_d<=0; de_d<=0; started<=0; bad_frame<=0; map_valid<=0;
        x<=0; y<=0; local_x<=0; local_y<=0; tile_x<=0; tile_y<=0;
        frame_pixels<=0;
        if(started && rejected_frames!=32'hffffffff) rejected_frames<=rejected_frames+1'b1;
        for(stat_index=0;stat_index<CELLS;stat_index=stat_index+1) begin
            sums[stat_index]<=0; shadow_counts[stat_index]<=0; strengths[stat_index]<=0;
        end
    end else begin
        vs_d<=vs; de_d<=de;
        if(start_frame) begin
            if(started) begin
                if(complete_frame) begin
                    map_valid<=1;
                    if(accepted_frames!=32'hffffffff) accepted_frames<=accepted_frames+1'b1;
                    for(stat_index=0;stat_index<CELLS;stat_index=stat_index+1)
                        strengths[stat_index]<=map_valid ?
                            approach(strengths[stat_index],shadow_target(sums[stat_index],shadow_counts[stat_index])) :
                            shadow_target(sums[stat_index],shadow_counts[stat_index]);
                end else if(rejected_frames!=32'hffffffff) rejected_frames<=rejected_frames+1'b1;
            end
            started<=1; bad_frame<=de;
            frame_pixels<=0; x<=0; y<=0; local_x<=0; local_y<=0; tile_x<=0; tile_y<=0;
            frame_mode<=mode;
            frame_manual<=(manual_strength>256)?9'd256:manual_strength;
            for(stat_index=0;stat_index<CELLS;stat_index=stat_index+1) begin
                sums[stat_index]<=0; shadow_counts[stat_index]<=0;
            end
        end else if(started) begin
            if(de) begin
                if(vs || x>=WIDTH || y>=HEIGHT) bad_frame<=1;
                if(x<WIDTH && y<HEIGHT && !vs) begin
                    sums[tile_y*GRID_X+tile_x]<=sums[tile_y*GRID_X+tile_x]+luminance;
                    if(luminance>4 && luminance<=64)
                        shadow_counts[tile_y*GRID_X+tile_x]<=shadow_counts[tile_y*GRID_X+tile_x]+1'b1;
                    frame_pixels<=frame_pixels+1'b1;
                    x<=x+1'b1;
                    if(local_x==TW-1) begin
                        local_x<=0;
                        if(tile_x<GRID_X-1) tile_x<=tile_x+1'b1;
                    end else local_x<=local_x+1'b1;
                end
            end
            if(line_end) begin
                if(width_bad) bad_frame<=1;
                x<=0; local_x<=0; tile_x<=0;
                if(y<HEIGHT) y<=y+1'b1;
                if(local_y==TH-1) begin
                    local_y<=0;
                    if(tile_y<GRID_Y-1) tile_y<=tile_y+1'b1;
                end else local_y<=local_y+1'b1;
            end
        end
    end
end

