function [8:0] target_strength;
    input [SUM_BITS-1:0] total;
    begin
        if(total<=TILE_PIXELS*32) target_strength=256;
        else if(total<=TILE_PIXELS*48) target_strength=224;
        else if(total<=TILE_PIXELS*64) target_strength=192;
        else if(total<=TILE_PIXELS*80) target_strength=160;
        else if(total<=TILE_PIXELS*96) target_strength=128;
        else if(total<=TILE_PIXELS*112) target_strength=96;
        else if(total<=TILE_PIXELS*128) target_strength=64;
        else if(total<=TILE_PIXELS*144) target_strength=32;
        else target_strength=0;
    end
endfunction
function [8:0] approach;
    input [8:0] old_value, target;
    begin
        if(target>old_value+9'd16) approach=old_value+9'd16;
        else if(old_value>target+9'd16) approach=old_value-9'd16;
        else approach=target;
    end
endfunction
// A coarse luminance histogram complements the mean. Bright lamps may lift
// the mean even when useful shadow pixels occupy much of the tile. Pixels
// 0..4 are excluded from this statistic and retain unity gain in both curves.
function [8:0] shadow_target;
    input [SUM_BITS-1:0] total;
    input [COUNT_BITS-1:0] count;
    reg [8:0] mean_strength, fraction_strength;
    begin
        mean_strength=target_strength(total);
        if(count >= (TILE_PIXELS*3+7)/8) fraction_strength=256;
        else if(count >= (TILE_PIXELS+3)/4) fraction_strength=224;
        else if(count >= (TILE_PIXELS+7)/8) fraction_strength=192;
        else if(count >= (TILE_PIXELS+15)/16) fraction_strength=128;
        else fraction_strength=0;
        shadow_target=(SHADOW_DETAIL && fraction_strength>mean_strength) ?
                      fraction_strength : mean_strength;
    end
endfunction
function [8:0] interpolate;
    input [8:0] a, c; input [7:0] fraction;
    reg signed [9:0] difference;
    reg signed [18:0] product;
    reg signed [19:0] value;
    begin
        // a*(256-f)+c*f == a*256+(c-a)*f. One signed multiplier.
        // Difference includes both +/-256; fraction is explicitly positive.
        difference=$signed({1'b0,c})-$signed({1'b0,a});
        product=difference*$signed({1'b0,fraction});
        value=($signed({11'd0,a})<<<8)+product+20'sd128;
        interpolate=value>>>8;
    end
endfunction
function [7:0] clip;
    input [11:0] value;
    begin clip=(value>255)?8'd255:value[7:0]; end
endfunction

reg vs_d, de_d, started, bad_frame, map_valid;
reg [11:0] x, y, local_x, local_y, tile_x, tile_y;
reg [31:0] frame_pixels, accepted_frames, rejected_frames;
reg [1:0] frame_mode;
reg [8:0] frame_manual;
wire start_frame=vs && !vs_d;
wire line_end=de_d && !de;
wire [12:0] completed_rows={1'b0,y}+(line_end?13'd1:13'd0);
