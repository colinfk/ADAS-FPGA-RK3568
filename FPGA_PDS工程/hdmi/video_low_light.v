// A small dark object remains visible even when lamps raise the tile mean.
// The floor fades continuously from 128 at Y=64 to zero at Y=128.
// Manual mode bypasses this floor, preserving an exact strength-zero bypass.
function [8:0] shadow_floor;
    input [7:0] value;
    begin
        if(value<=4 || value>=128) shadow_floor=0;
        else if(value<=64) shadow_floor=128;
        else shadow_floor=(9'd128-{1'b0,value})<<1;
    end
endfunction
