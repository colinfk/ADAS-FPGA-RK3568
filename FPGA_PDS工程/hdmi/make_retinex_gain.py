"""Generate a small Q3.9 gain table; no runtime variable division or file ROM."""
from pathlib import Path
import json

ANCHORS = ((0,0),(4,4),(8,24),(16,64),(32,112),(64,168),
           (96,200),(128,218),(160,232),(192,242),(224,250),(255,255))

def tone(value):
    for (a,b),(c,d) in zip(ANCHORS, ANCHORS[1:]):
        if value <= c:
            return b+((value-a)*(d-b)+(c-a)//2)//(c-a)
    return 255

def gain(value):
    return 512 if value <= 4 else min(1792,(tone(value)*512+value//2)//value)

def render():
    lines=['// Generated by make_retinex_gain.py. Unity=512, maximum=1792.',
           'function [10:0] retinex_gain_q9;', '    input [7:0] value;',
           '    begin', '        case(value)']
    for start in range(0,256,4):
        lines.append('            '+' '.join(f"8'd{v}: retinex_gain_q9=11'd{gain(v)};" for v in range(start,start+4)))
    lines += ["            default: retinex_gain_q9=11'd512;", '        endcase', '    end', 'endfunction']
    return '\n'.join(lines)+'\n'

if __name__ == '__main__':
    path=Path(__file__).with_name('video_retinex_light.v')
    text=path.read_text(encoding='utf-8')
    before, body=text.split('// RETINEX_LUT_BEGIN\n',1)
    _, after=body.split('// RETINEX_LUT_END',1)
    path.write_text(before+'// RETINEX_LUT_BEGIN\n'+render()+'// RETINEX_LUT_END'+after,encoding='utf-8')
    print(json.dumps(dict(entries=256, unity=512, max_gain=1792, runtime_division=False)))
