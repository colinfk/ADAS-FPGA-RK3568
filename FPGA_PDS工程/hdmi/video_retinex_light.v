`timescale 1ns/1ps
// Single-scale Retinex approximation. The 5x5 neighborhood is causal, anchored
// at the current pixel, so RGB has no row delay or frame-memory requirement.
// Top four rows use the current V; left edge repeats the first vertical value.
module video_retinex_light #(
    parameter integer WIDTH=1920, HEIGHT=1080, GRID_X=8, GRID_Y=6
) (
    input pix_clk,rst_n,rx_ready,vs,hs,de,
    input [7:0] r,g,b,
    input [1:0] mode,
    input [8:0] manual_strength,
    output out_ready,out_vs,out_hs,out_de,
    output reg [7:0] out_r,out_g,out_b,
    output [127:0] diagnostic
);
wire [11:0] x,y;
wire [8:0] region_strength;
wire region_process;
wire [127:0] region_diag;
// Reuse only the already validated complete-frame statistics and interpolation.
// Its RGB outputs are unconnected: the old tone-mapping datapath is dead logic.
video_low_light #(.WIDTH(WIDTH),.HEIGHT(HEIGHT),.GRID_X(GRID_X),.GRID_Y(GRID_Y),.SHADOW_DETAIL(2)) statistics (
    .pix_clk(pix_clk),.rst_n(rst_n),.rx_ready(rx_ready),.vs(vs),.hs(hs),.de(de),
    .r(r),.g(g),.b(b),.mode(mode),.manual_strength(manual_strength),
    .out_ready(),.out_vs(),.out_hs(),.out_de(),.out_r(),.out_g(),.out_b(),
    .diagnostic(region_diag),.sample_x(x),.sample_y(y),
    .sample_strength(region_strength),.sample_process(region_process));
wire [7:0] maximum=(r>g)?((r>b)?r:b):((g>b)?g:b);
wire valid_pixel=rx_ready && de && !vs && x<WIDTH && y<HEIGHT;

// Four independent circular row banks. Read old data and overwrite only the
// oldest bank. No reset on RAM contents: warm rows never consume stale data.
reg [7:0] line0[0:WIDTH-1],line1[0:WIDTH-1],line2[0:WIDTH-1],line3[0:WIDTH-1];
reg [7:0] mem0,mem1,mem2,mem3,v0;
reg [1:0] bank0;
reg top0,left0,left1;
always @(posedge pix_clk) begin
    if(valid_pixel) begin
        mem0<=line0[x];mem1<=line1[x];mem2<=line2[x];mem3<=line3[x];
        case(y[1:0])
            0:line0[x]<=maximum;
            1:line1[x]<=maximum;
            2:line2[x]<=maximum;
            3:line3[x]<=maximum;
        endcase
    end
end

function [7:0] smooth5;
    input [7:0] a,c,d,e,f;
    reg [11:0] total;
    begin
        // Extend operands before shifts; the sum is at most 4080.
        total={4'd0,a}+({4'd0,c}<<2)+({4'd0,d}<<2)+({4'd0,d}<<1)+({4'd0,e}<<2)+{4'd0,f}+12'd8;
        smooth5=total>>4;
    end
endfunction
