"""Generate deterministic Q3.9 shadow/highlight ROMs inside video_low_light.v."""
from pathlib import Path

LEGACY_ANCHORS = ((0, 0), (4, 4), (16, 34), (32, 84), (64, 148), (96, 184),
           (128, 208), (160, 224), (192, 236), (224, 246), (255, 255))
ANCHORS = ((0, 0), (4, 4), (8, 12), (16, 48), (32, 104), (64, 160),
           (96, 192), (128, 212), (160, 228), (192, 240), (224, 248), (255, 255))
CHANNEL_ANCHORS = ((0,0),(4,4),(8,24),(16,64),(32,112),(64,168),
                   (96,200),(128,218),(160,232),(192,242),(224,250),(255,255))

def tone(y, profile=1):
    anchors = CHANNEL_ANCHORS if profile==2 else (ANCHORS if profile else LEGACY_ANCHORS)
    for (x0, y0), (x1, y1) in zip(anchors, anchors[1:]):
        if y <= x1:
            return y0 + ((y-x0)*(y1-y0) + (x1-x0)//2)//(x1-x0)
    return 255

def shadow_gain(y, profile=1):
    return 512 if y == 0 else min(2048, (tone(y, profile)*512 + y//2)//y)

def headroom(maximum):
    return 2048 if maximum == 0 else min(2048, (255*512)//maximum)

def render_rom(name, values):
    lines = [f'function [11:0] {name};', '    input [7:0] value;', '    begin', '        case(value)']
    for start in range(0, 256, 4):
        lines.append('            ' + ' '.join(f"8'd{i}: {name}=12'd{values[i]};" for i in range(start, start+4)))
    lines += [f"            default: {name}=12'd512;", '        endcase', '    end', 'endfunction']
    return '\n'.join(lines)

def generated():
    legacy = render_rom('shadow_gain_q9', [shadow_gain(i, 0) for i in range(256)])
    stronger = render_rom('shadow_gain_q9', [shadow_gain(i, 1) for i in range(256)])
    legacy_case = legacy[legacy.index('        case(value)'):legacy.index('\n    end\nendfunction')]
    stronger_case = stronger[stronger.index('        case(value)'):stronger.index('\n    end\nendfunction')]
    shadow = ('function [11:0] shadow_gain_q9;\n    input [7:0] value;\n    begin\n'
              '        if (SHADOW_DETAIL == 0) begin\n' + legacy_case + '\n        end else begin\n'
              + stronger_case + '\n        end\n    end\nendfunction')
    # v9 applies a bounded transfer independently to each channel. The
    # delta is nonnegative and C + delta never exceeds 255.
    return shadow + '\n' + \
        render_rom('headroom_q9', [headroom(i) for i in range(256)]) + '\n' + \
        render_rom('channel_delta', [tone(i, 2)-i for i in range(256)])

if __name__ == '__main__':
    path = Path(__file__).with_name('video_low_light.v')
    source = path.read_text(encoding='utf-8')
    start, end = '// LUT_BEGIN - regenerated by make_low_light_lut.py, no runtime divide/power.', '// LUT_END'
    before, tail = source.split(start, 1)
    _, after = tail.split(end, 1)
    path.write_text(before + start + '\n' + generated() + '\n' + end + after, encoding='utf-8')
    print('Generated legacy/v8 shadow curves and headroom ROM; profile folds at synthesis')
